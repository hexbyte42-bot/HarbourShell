#!/usr/bin/env python3
"""Rasterise Natural Earth 110m land (public domain) into src/launcher/worldmap_data.rs.

usage: tools/gen_worldmap.py ne_110m_land.json > src/launcher/worldmap_data.rs
Equirectangular, longitude -180..180, latitude LAT_TOP..LAT_BOTTOM, 1 bit per pixel.
"""
import json, sys

W, H = 312, 121
LAT_TOP, LAT_BOTTOM = 83.0, -57.0

def rings_of(geom):
    if geom["type"] == "Polygon":
        yield geom["coordinates"]
    elif geom["type"] == "MultiPolygon":
        for poly in geom["coordinates"]:
            yield poly

def main(path):
    data = json.load(open(path))
    land = [[False] * W for _ in range(H)]
    for feat in data["features"]:
        for poly in rings_of(feat["geometry"]):
            edges = []
            for ring in poly:
                for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
                    if y1 != y2:
                        edges.append((x1, y1, x2, y2))
            for row in range(H):
                lat = LAT_TOP - (row + 0.5) * (LAT_TOP - LAT_BOTTOM) / H
                xs = []
                for x1, y1, x2, y2 in edges:
                    if (y1 <= lat < y2) or (y2 <= lat < y1):
                        xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
                xs.sort()
                for a, b in zip(xs[0::2], xs[1::2]):
                    c0 = max(0, int(round((a + 180) / 360 * W - 0.5)))
                    c1 = min(W - 1, int(round((b + 180) / 360 * W - 0.5)))
                    for col in range(c0, c1 + 1):
                        land[row][col] = True
    row_bytes = (W + 7) // 8
    out = []
    out.append("//! Generated by tools/gen_worldmap.py from Natural Earth 110m land (public domain).")
    out.append("//! Equirectangular, longitude -180..180, latitude %.0f..%.0f, 1 bit per pixel, MSB first." % (LAT_TOP, LAT_BOTTOM))
    out.append("")
    out.append("pub const W: usize = %d;" % W)
    out.append("pub const H: usize = %d;" % H)
    out.append("pub const LAT_TOP: f32 = %.1f;" % LAT_TOP)
    out.append("pub const LAT_BOTTOM: f32 = %.1f;" % LAT_BOTTOM)
    out.append("pub const ROW_BYTES: usize = %d;" % row_bytes)
    out.append("")
    out.append("pub static LAND: [u8; %d] = [" % (row_bytes * H))
    for r in range(H):
        bs = []
        for b in range(row_bytes):
            v = 0
            for k in range(8):
                col = b * 8 + k
                if col < W and land[r][col]:
                    v |= 0x80 >> k
            bs.append("0x%02x" % v)
        out.append("    " + ", ".join(bs) + ",")
    out.append("];")
    print("\n".join(out))
    n = sum(sum(r) for r in land)
    print("land pixels: %d of %d (%.1f%%)" % (n, W * H, 100.0 * n / (W * H)), file=sys.stderr)

main(sys.argv[1])
