#!/usr/bin/env python3
"""Write THIRD_PARTY_LICENSES.md: the Rust crates the build links (from `cargo metadata`), with licence
expression and source URL. Regenerate after changing Cargo.toml / Cargo.lock:

    python3 tools/gen_third_party_licenses.py > THIRD_PARTY_LICENSES.md

Only crates reachable from this package for the normal (non-dev, non-build) graph on the targets that
matter (Linux/macOS native, Emscripten web) are listed; platform crates for Windows/Android/Haiku/wasm-bindgen
that Cargo.lock mentions for chrono's optional backends are listed too, under "also in Cargo.lock".
"""
import json, subprocess, sys

m = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"]))
byid = {p["id"]: p for p in m["packages"]}
root = m["resolve"]["root"]
nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

def row(p):
    url = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
    return f"| [{p['name']}]({url}) | {p['version']} | {p['license'] or 'UNKNOWN'} |"

print("# Rust crate licences\n")
print("Generated by `tools/gen_third_party_licenses.py` from `cargo metadata --locked`. Do not edit by hand.\n")
print("Each crate is used under the licence shown (for `A OR B`, under either one; Harbour Shell takes the MIT option where offered).\n")
print("| crate | version | licence |\n|---|---|---|")
for p in sorted((byid[i] for i in seen if i != root), key=lambda p: p["name"]):
    print(row(p))
rest = [p for i, p in byid.items() if i not in seen and i != root]
print("\n## Also in Cargo.lock (optional or other-platform backends; not linked into the Linux/macOS build)\n")
print("| crate | version | licence |\n|---|---|---|")
for p in sorted(rest, key=lambda p: p["name"]):
    print(row(p))
